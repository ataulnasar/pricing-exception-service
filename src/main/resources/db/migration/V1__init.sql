-- Schema for the pricing exception service. Portable SQL: runs unchanged on H2 and PostgreSQL.
-- No partial indexes, no generated (computed) columns. See docs/design.md "Tables".
-- No CHECK (... IN (...)) constraints on the enum columns: H2 2.4.240 cannot evaluate them when the
-- insert comes from a different session than the one that ran this migration. The allowed values are
-- enforced by the domain enums and the JPA mapping.

CREATE TABLE app_user (
    id                 VARCHAR(64)  NOT NULL,
    name               VARCHAR(200) NOT NULL,
    role               VARCHAR(32)  NOT NULL,
    approval_limit_bps INTEGER,
    CONSTRAINT pk_app_user PRIMARY KEY (id)
);

CREATE TABLE mortgage_application (
    id                VARCHAR(64)  NOT NULL,
    customer_ref      VARCHAR(100) NOT NULL,
    standard_rate_bps INTEGER      NOT NULL,
    status            VARCHAR(32)  NOT NULL,
    owner_rm_id       VARCHAR(64)  NOT NULL,
    CONSTRAINT pk_mortgage_application PRIMARY KEY (id),
    CONSTRAINT fk_mortgage_application_owner FOREIGN KEY (owner_rm_id) REFERENCES app_user (id)
);

CREATE TABLE pricing_exception_request (
    id                    UUID         NOT NULL,
    application_id        VARCHAR(64)  NOT NULL,
    requested_by          VARCHAR(64)  NOT NULL,
    discount_bps          INTEGER      NOT NULL,
    reason                VARCHAR(500) NOT NULL,
    status                VARCHAR(32)  NOT NULL,
    supersedes_id         UUID,
    decided_by            VARCHAR(64),
    decided_at            TIMESTAMP WITH TIME ZONE,
    decision_comment      VARCHAR(500),
    approved_discount_bps INTEGER,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    version               BIGINT       NOT NULL,
    -- = application_id while the request is PENDING or APPROVED, else NULL. Set by the code on
    -- every status change. The UNIQUE index below gives INV-04 (NULLs do not collide).
    active_application_id VARCHAR(64),
    CONSTRAINT pk_pricing_exception_request PRIMARY KEY (id),
    CONSTRAINT fk_per_application FOREIGN KEY (application_id) REFERENCES mortgage_application (id),
    CONSTRAINT fk_per_requested_by FOREIGN KEY (requested_by) REFERENCES app_user (id),
    CONSTRAINT fk_per_decided_by FOREIGN KEY (decided_by) REFERENCES app_user (id),
    CONSTRAINT fk_per_supersedes FOREIGN KEY (supersedes_id) REFERENCES pricing_exception_request (id),
    CONSTRAINT ck_per_discount CHECK (discount_bps >= 1),
    CONSTRAINT ck_per_active CHECK (active_application_id IS NULL OR active_application_id = application_id)
);

CREATE UNIQUE INDEX ux_per_active_application ON pricing_exception_request (active_application_id);
CREATE INDEX ix_per_application ON pricing_exception_request (application_id);
CREATE INDEX ix_per_status ON pricing_exception_request (status);

-- Insert only: history of every status change (INV-02).
CREATE TABLE request_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id  UUID        NOT NULL,
    type        VARCHAR(32) NOT NULL,
    actor_id    VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    from_status VARCHAR(32),
    to_status   VARCHAR(32) NOT NULL,
    comment     VARCHAR(500),
    CONSTRAINT pk_request_event PRIMARY KEY (id),
    CONSTRAINT fk_request_event_request FOREIGN KEY (request_id) REFERENCES pricing_exception_request (id)
);

CREATE INDEX ix_request_event_request ON request_event (request_id);

-- Idempotency-Key replay store (used from Phase 4).
CREATE TABLE idempotency_record (
    caller_id       VARCHAR(64)   NOT NULL,
    idem_key        VARCHAR(128)  NOT NULL,
    request_hash    VARCHAR(64)   NOT NULL,
    response_status INTEGER       NOT NULL,
    response_body   VARCHAR(16000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_idempotency_record PRIMARY KEY (caller_id, idem_key)
);
